def main():
    ap = argparse.ArgumentParser(); ap.add_argument('bt'); ap.add_argument('out'); ap.add_argument('--book', default='96mid1ogzk')
    a = ap.parse_args()
    base = glob.glob(str(Path(a.bt) / f'*/*/*/*/{a.book}/default'))[0]
    occ = collections.defaultdict(list)
    for v in ('002', '003'):
        T = ''.join(c['c'] for p in json.load(open(f'{base}/{v}.char.json'))['pages'] for col in p['columns'] for c in col['cells'])
        for e in json.load(open(f'{base}/{v}.entity.json'))['entities']:
            if e['type'] == 'people' and e['target']['status'] == 'new_candidate':
                o, L = e['span']['start_offset'], e['span']['end_offset']
                occ[e['text']].append((v, e['anchor']['start'], T[max(0, o - 14):o] + '【' + e['text'] + '】' + T[L:L + 14]))
    tot = sum(len(x) for x in occ.values())
    known = set(B) | set(R) | set(N)
    miss = [k for k in occ if k not in known]
    if miss: print('未判读：', miss); sys.exit(1)
    bs = {k: v for k, v in B.items() if k in occ and v[2] != '—'}
    rs = {k: v for k, v in R.items() if k in occ}
    for k, v in B.items():
        if v[2] == '—' and k in occ: rs[k] = (v[0] + ' hixhd2h9bfmq', '异体 愼＝慎')
    ns = {k: v for k, v in N.items() if k in occ}
    nb = sum(len(occ[k]) for k in bs); nr = sum(len(occ[k]) for k in rs); nn = sum(len(occ[k]) for k in ns)
